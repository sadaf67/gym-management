namespace Tahila.Domain.Entities;

// ─────────────────────────────────────────────────────────────────────────────
// این کلاس "پکیج‌های عضویت" رو نگه میداره
// هر پکیج یه نوع اشتراک باشگاهه — مثلاً ماهانه، فصلی، سالانه
// کاربر یه پکیج رو میخره و تا پایان مدت اون میتونه از باشگاه استفاده کنه
// ─────────────────────────────────────────────────────────────────────────────
public class Plan : BaseEntity
{
    // اسم پکیج — مثلاً "پکیج یک ماهه" یا "اشتراک طلایی"
    public string Name { get; set; } = string.Empty;

    // توضیح پکیج — این پکیج چه امکاناتی شامل میشه
    public string? Description { get; set; }

    // قیمت — به تومان، بدون اعشار (مثلاً 500000 = پانصد هزار تومان)
    // توی دیتابیس decimal(18,0) ذخیره میشه — بدون ریال‌های کسری
    public decimal Price { get; set; }

    // مدت اشتراک — به روز
    // مثلاً: 30 = یک ماه، 90 = سه ماه، 365 = یک سال
    public int DurationDays { get; set; }

    // ویژگی‌های پکیج — لیست امکانات جدا شده با "|" یا JSON
    // مثلاً: "استخر|سونا|جکوزی|رختکن اختصاصی"
    public string? Features { get; set; }

    // پرطرفدار؟ — اگه true باشه، این پکیج با یه برچسب "محبوب‌ترین" نمایش داده میشه
    public bool IsPopular { get; set; } = false;

    // ترتیب نمایش — پکیج با عدد کمتر اول نشون داده میشه
    public int Order { get; set; } = 0;

    // فعال/غیرفعال — پکیج غیرفعال توی سایت نشون داده نمیشه
    public bool IsActive { get; set; } = true;

    // شامل برنامه غذایی؟
    // اگه true باشه، کاربری که این پکیج رو خریده میتونه
    // برنامه غذایی هوشمند رو دانلود کنه
    public bool HasDietPlan { get; set; } = false;

    // لیست اشتراک‌های خریداری شده برای این پکیج
    // یعنی کدوم کاربرها این پکیج رو خریدن
    public ICollection<Subscription> Subscriptions { get; set; } = new List<Subscription>();
}
