namespace Tahila.Domain.Entities;

// ─────────────────────────────────────────────────────────────────────────────
// این کلاس "پدر" همه موجودیت‌های پروژه‌ست
// یعنی هر چیزی که توی دیتابیس ذخیره میشه (مقاله، مربی، کلاس، ...) از این ارث می‌بره
// و به‌طور خودکار این سه تا فیلد رو داره
// ─────────────────────────────────────────────────────────────────────────────
public abstract class BaseEntity
{
    // شناسه یکتا — دیتابیس این رو خودش اضافه میکنه (مثل شماره ملی برای هر رکورد)
    public int Id { get; set; }

    // تاریخ و ساعت لحظه‌ای که این رکورد ساخته شد — پیشفرض: همین الان
    public DateTime CreatedAt { get; set; } = DateTime.Now;

    // تاریخ آخرین ویرایش — اگه هنوز ویرایش نشده null هست
    public DateTime? UpdatedAt { get; set; }

    // این یه تکنیک به اسم "حذف نرم" (Soft Delete) هست
    // وقتی حذف می‌کنیم، رکورد رو واقعاً از دیتابیس پاک نمی‌کنیم
    // فقط این رو true می‌کنیم و دیگه توی سایت نشونش نمیدیم
    // مزیتش اینه که اگه اشتباهی حذف کردیم می‌تونیم برگردونیم
    public bool IsDeleted { get; set; } = false;
}
