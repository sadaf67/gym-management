namespace Tahila.Domain.Entities;

// ─────────────────────────────────────────────────────────────────────────────
// این کلاس "تنظیمات کلی سایت" رو نگه میداره
// یعنی اطلاعاتی که ادمین از پنل تغییر میده و توی همه صفحات استفاده میشه
// مثلاً اسم باشگاه، آدرس، رنگ اصلی سایت، و ...
// معمولاً فقط یه ردیف توی دیتابیس داریم — همیشه Id = 1
// ─────────────────────────────────────────────────────────────────────────────
public class SiteSetting : BaseEntity
{
    // ════════════════════════════════════════════════════════════════
    //   اطلاعات سئو — برای نمایش توی گوگل
    // ════════════════════════════════════════════════════════════════

    // اسم سایت — نشون داده میشه توی تب مرورگر و نتایج گوگل
    public string SiteName { get; set; } = "تهیلا";

    // توضیح کوتاه سایت — زیر اسم سایت توی گوگل نشون داده میشه
    public string? SiteDescription { get; set; }

    // کلمات کلیدی — برای گوگل که بفهمه این سایت درباره چیه
    // مثلاً: "باشگاه، ورزش، تهران، بدنسازی"
    public string? SiteKeywords { get; set; }

    // ════════════════════════════════════════════════════════════════
    //   ظاهر سایت
    // ════════════════════════════════════════════════════════════════

    // مسیر لوگو — عکس آرم باشگاه که بالای سایت نشون داده میشه
    public string? Logo { get; set; }

    // آیکون مرورگر — اون عکس کوچیک که توی تب مرورگر نشون داده میشه
    public string? Favicon { get; set; }

    // ════════════════════════════════════════════════════════════════
    //   بخش Hero — اون تصویر بزرگ بالای صفحه اصلی
    // ════════════════════════════════════════════════════════════════

    // عنوان بزرگ وسط صفحه — مثلاً "به باشگاه تهیلا خوش آمدید"
    public string? HeroTitle { get; set; }

    // زیرعنوان — مثلاً "قوی‌تر، سالم‌تر، بهتر"
    public string? HeroSubTitle { get; set; }

    // عکس پس‌زمینه hero — اگه ویدیو نداریم این عکس نشون داده میشه
    public string? HeroImage { get; set; }

    // لینک ویدیو — اگه بخوایم به جای عکس، ویدیو پخش بشه
    public string? HeroVideoUrl { get; set; }

    // ════════════════════════════════════════════════════════════════
    //   بخش "درباره ما"
    // ════════════════════════════════════════════════════════════════

    // عنوان بخش درباره ما
    public string? AboutTitle { get; set; }

    // متن توضیحات درباره ما — تاریخچه باشگاه، ارزش‌ها، ...
    public string? AboutText { get; set; }

    // عکس بخش درباره ما
    public string? AboutImage { get; set; }

    // ════════════════════════════════════════════════════════════════
    //   اطلاعات تماس
    // ════════════════════════════════════════════════════════════════

    // آدرس فیزیکی باشگاه
    public string? Address { get; set; }

    // شماره تلفن اصلی
    public string? Phone { get; set; }

    // شماره تلفن دوم — اگه دو خط داریم
    public string? Phone2 { get; set; }

    // ایمیل باشگاه
    public string? Email { get; set; }

    // ساعات کاری — مثلاً "شنبه تا پنج‌شنبه: ۷ الی ۲۳"
    public string? WorkingHours { get; set; }

    // ════════════════════════════════════════════════════════════════
    //   شبکه‌های اجتماعی
    // ════════════════════════════════════════════════════════════════

    // لینک اینستاگرام باشگاه
    public string? Instagram { get; set; }

    // لینک کانال تلگرام
    public string? Telegram { get; set; }

    // شماره واتساپ — برای پشتیبانی آنلاین
    public string? WhatsApp { get; set; }

    // کد embed نقشه گوگل مپ — اون iframe که آدرس باشگاه رو نشون میده
    public string? MapEmbed { get; set; }

    // ════════════════════════════════════════════════════════════════
    //   آمار برای نمایش توی صفحه اصلی
    //   این اعداد دستی وارد میشن و به کاربرها نشون داده میشن
    //   مثلاً: "500+ عضو"
    // ════════════════════════════════════════════════════════════════

    // تعداد کل اعضا — برای نشون دادن توی بخش آمار
    public int? MembersCount { get; set; }

    // تعداد مربیان
    public int? CoachesCount { get; set; }

    // تعداد کلاس‌ها
    public int? ClassesCount { get; set; }

    // سال‌های فعالیت باشگاه
    public int? YearsCount { get; set; }

    // ════════════════════════════════════════════════════════════════
    //   فوتر سایت
    // ════════════════════════════════════════════════════════════════

    // متن پایین صفحه — مثلاً "تمامی حقوق متعلق به باشگاه تهیلا می‌باشد"
    public string? FooterText { get; set; }

    // رنگ اصلی سایت — کد hex رنگ — پیشفرض: صورتی (#FF2D78)
    // ادمین میتونه رنگ کل سایت رو از اینجا عوض کنه
    public string? PrimaryColor { get; set; } = "#FF2D78";
}
