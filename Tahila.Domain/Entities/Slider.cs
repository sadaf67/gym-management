namespace Tahila.Domain.Entities;

// ─────────────────────────────────────────────────────────────────────────────
// این کلاس "اسلایدر صفحه اصلی" رو نشون میده
// اسلایدر یعنی اون عکس‌های بزرگی که بالای صفحه اصلی سایت، یکی یکی میچرخن
// هر ردیف توی این جدول = یه اسلاید (یه عکس با یه دکمه)
// ─────────────────────────────────────────────────────────────────────────────
public class Slider : BaseEntity
{
    // عنوان اسلاید — متن بزرگ که روی عکس نشون داده میشه
    // مثلاً: "بهترین باشگاه تهران"
    public string Title { get; set; } = string.Empty;

    // زیرعنوان — متن کوچکتر زیر عنوان
    // مثلاً: "با بهترین مربیان"
    public string? SubTitle { get; set; }

    // متن دکمه — نوشته روی دکمه‌ای که توی اسلاید هست
    // مثلاً: "همین الان ثبت‌نام کن"
    public string? ButtonText { get; set; }

    // لینک دکمه — وقتی کاربر دکمه رو کلیک کرد کجا بره
    // مثلاً: "/Plans" یا "/Register"
    public string? ButtonLink { get; set; }

    // مسیر عکس — آدرس فایل عکس اسلاید توی سرور
    // مثلاً: "images/sliders/hero1.jpg"
    public string ImagePath { get; set; } = string.Empty;

    // ترتیب نمایش — اسلاید با عدد کمتر اول نشون داده میشه
    // مثلاً: Order=1 اول میاد، Order=2 دومی، ...
    public int Order { get; set; } = 0;

    // فعال/غیرفعال — اگه false بشه، این اسلاید توی سایت نشون داده نمیشه
    public bool IsActive { get; set; } = true;
}
