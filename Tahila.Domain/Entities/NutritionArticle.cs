namespace Tahila.Domain.Entities;

// ─────────────────────────────────────────────────────────────────────────────
// این کلاس یه مقاله تغذیه رو نشون میده
// مثلاً مقاله "پروتئین چیه و چقدر بخوریم" — همه اطلاعاتش اینجاست
// ─────────────────────────────────────────────────────────────────────────────
public class NutritionArticle : BaseEntity
{
    // عنوان مقاله که توی صفحه نشون داده میشه
    // مثل: "راهنمای کامل پروتئین برای عضله‌سازی"
    public string Title { get; set; } = string.Empty;

    // اسلاگ = بخش URL مقاله — فقط حروف انگلیسی، اعداد، خط تیره
    // مثلاً: "protein-guide-for-muscle-growth-123456"
    // این توی آدرس سایت استفاده میشه: /nutrition/protein-guide-...
    public string Slug { get; set; } = string.Empty;

    // خلاصه کوتاه مقاله — حدود 2-3 جمله
    // توی لیست مقالات نشون داده میشه تا کاربر تصمیم بگیره کلیک کنه یا نه
    public string Summary { get; set; } = string.Empty;

    // متن کامل مقاله — می‌تونه HTML باشه
    // یعنی ادمین می‌تونه با تگ‌های HTML طراحی کنه (بولد، ایتالیک، عکس، ...)
    public string Content { get; set; } = string.Empty;

    // دسته‌بندی مقاله — مثل "کاهش وزن" یا "عضله‌سازی" یا "ویتامین‌ها"
    // برای فیلتر کردن توی لیست استفاده میشه
    public string Category { get; set; } = string.Empty;

    // برچسب‌ها — کلمات کلیدی که با کاما جدا شدن
    // مثل: "پروتئین,عضله,وزنه" — برای سئو و جستجو مفیده
    public string? Tags { get; set; }

    // آدرس تصویر شاخص مقاله — می‌تونه URL اینترنتی یا مسیر فایل محلی باشه
    public string? ThumbnailUrl { get; set; }

    // اسم نویسنده — پیشفرض کارشناس تغذیه باشگاه هست
    public string AuthorName { get; set; } = "دکتر تغذیه تهیلا";

    // تخمین زمان خواندن مقاله به دقیقه — نشون میدیم کنار عنوان
    public int ReadMinutes { get; set; } = 5;

    // تعداد دفعاتی که این مقاله باز شده — هر بار که کسی مقاله رو باز کنه یه واحد اضافه میشه
    public int ViewCount { get; set; } = 0;

    // اگه true باشه، این مقاله "ویژه" هست و اول از همه نشون داده میشه
    // با ستاره ⭐ مشخص میشه
    public bool IsFeatured { get; set; } = false;

    // اگه false باشه، مقاله "پیش‌نویس" هست و توی سایت نشون داده نمیشه
    // ادمین می‌تونه بنویسه و بعداً منتشر کنه
    public bool IsPublished { get; set; } = true;

    // ترتیب نمایش — عدد کمتر = اول‌تر نشون داده میشه
    public int Order { get; set; } = 0;
}
