namespace Tahila.Domain.Entities;

// ─────────────────────────────────────────────────────────────────────────────
// این کلاس "مربیان باشگاه" رو نگه میداره
// هر مربی یه ردیف توی این جدول داره با عکس، تخصص، و بیوگرافیش
// توی صفحه اصلی سایت، کارت مربیان از اینجا لود میشه
// ─────────────────────────────────────────────────────────────────────────────
public class Coach : BaseEntity
{
    // اسم کامل مربی — مثلاً "علی محمدی"
    public string FullName { get; set; } = string.Empty;

    // تخصص — مثلاً "بدنسازی"، "یوگا"، "بوکس"
    public string? Specialty { get; set; }

    // بیوگرافی — توضیح کوتاه درباره مربی، سابقه کاری، مدارک
    public string? Bio { get; set; }

    // مسیر عکس مربی — آدرس فایل عکس توی سرور
    public string? ImagePath { get; set; }

    // لینک اینستاگرام مربی — اگه داشت نشون داده میشه
    public string? Instagram { get; set; }

    // ترتیب نمایش — مربی با عدد کمتر اول نشون داده میشه
    public int Order { get; set; } = 0;

    // فعال/غیرفعال — مربی غیرفعال توی سایت نشون داده نمیشه
    public bool IsActive { get; set; } = true;

    // لیست کلاس‌هایی که این مربی تدریس میکنه
    // یه مربی میتونه چند کلاس داشته باشه — مثلاً هم بدنسازی هم کراسفیت
    // EF Core این لیست رو خودکار از جدول GymClass پر میکنه
    public ICollection<GymClass> Classes { get; set; } = new List<GymClass>();
}
